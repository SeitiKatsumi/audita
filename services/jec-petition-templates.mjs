export function renderJecPetitionTemplate(templateId, values = {}) {
  const template = getJecPetitionTemplate(templateId);
  if (!template) throw new Error("jec_petition_template_not_found");
  return template.text.replace(/\{\{([A-Z_]+)\}\}/g, (_match, key) => {
    const value = String(values[key] ?? "").trim();
    return value || `[PENDENTE: ${key}]`;
  });
}
